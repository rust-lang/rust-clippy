fn chains() {
    let x = 1;
    let y = 2;
    let a = true;
    let b = false;
    let z = || true;
    let w = || true;

    // Merging across terms without side effects is always fine
    let _ = x == y || a || x < y; //~ double_comparisons
    let _ = x != y && a && x <= y; //~ double_comparisons
    let _ = x == y || a || b || x < y; //~ double_comparisons

    // Merging across a call is `MaybeIncorrect`: `z()` would no longer be called when `x < y`
    let _ = x == y || z() || x < y; //~ double_comparisons
    let _ = x != y && z() && x <= y; //~ double_comparisons
    let _ = x == y || z() || x < y || z(); //~ double_comparisons
    let _ = x == y || w() || z() || x < y; //~ double_comparisons
    let _ = w() || x == y || z() || x < y; //~ double_comparisons

    // Terms after or before the merged comparisons are unaffected
    let _ = x == y || x < y || z(); //~ double_comparisons
    let _ = z() || x == y || x < y; //~ double_comparisons
}

fn no_lint_in_chains() {
    let x = 1;
    let y = 2;
    let w = 3;
    let z = || true;
    let f = || 1;

    // Different operands
    let _ = x == y || z() || x < w;
    let _ = x != y && z() && w <= y;

    // Operators that can't be merged
    let _ = x < y || z() || x < y;
    let _ = x == y || z() || x != y;
    let _ = x <= y && z() && x <= y;

    // The operands have side effects
    let _ = f() == y || z() || f() < y;

    // The comparisons are in different chains
    let _ = (x == y && z()) || x < y;
    let _ = (x == y || z()) && x < y;
}

fn nested_and_parenthesized() {
    let x = 1;
    let y = 2;
    let z = || true;
    let w = || true;

    let _ = (x == y) || (x < y); //~ double_comparisons
    let _ = x == y || (x < y || (z() || w())); //~ double_comparisons
    let _ = ((x == y || x < y) || z()) || w(); //~ double_comparisons
    let _ = x == y || (x < y || z()) || w(); //~ double_comparisons

    // A chain nested in a different operator is linted on its own
    let _ = (x <= y && x >= y) || z(); //~ double_comparisons
    let _ = (x == y || x < y) && z(); //~ double_comparisons

    // The parentheses are kept when the merged result is still a chain
    let _ = w() && ((x == y || x < y || z()) && x > y); //~ double_comparisons
    let _ = !(x == y || x < y || z()); //~ double_comparisons
    let _ = (x != y && z() && x <= y) || w(); //~ double_comparisons
}

macro_rules! lt {
    ($x:ident, $y:ident) => {
        $x < $y
    };
}

macro_rules! eq_or_lt {
    ($x:ident, $y:ident) => {
        $x == $y || $x < $y
    };
}

macro_rules! or_true {
    ($e:expr) => {
        $e || true
    };
}

fn macros() {
    let a = 1;
    let b = 2;
    let z = || true;

    // Comparisons and chains generated by a macro are not merged
    let _ = a == b || lt!(a, b);
    let _ = a == b || z() || lt!(a, b);
    let _ = a == b || eq_or_lt!(a, b);

    // A chain written by the user inside a macro argument is still linted
    let _ = or_true!(a == b || a < b); //~ double_comparisons
}
