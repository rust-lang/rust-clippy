use clippy_config::Conf;
use clippy_utils::diagnostics::span_lint_and_sugg;
use clippy_utils::source::snippet_indent;
use rustc_attr_ir::find_attr;
use rustc_errors::Applicability;
use rustc_hir::{Item, ItemKind};
use rustc_lint::{LateContext, LateLintPass, LintContext as _, impl_lint_pass};

declare_clippy_lint! {
    /// ### What it does
    /// Checks for exported structs, enums, and unions without `#[must_use]`, regardless
    /// of whether they contain resources or implement `Drop`.
    ///
    /// By default, structs with no fields and enums with exactly one variant and no fields
    /// are ignored. A struct or enum variant with fields is checked even if all its fields
    /// have zero-sized types. Enums with multiple variants are checked even if none have fields.
    ///
    /// Set `check-private-items = true` to also check types that are not exported, and
    /// `missing-must-use-on-empty = true` to also check structs with no fields and enums with
    /// exactly one variant and no fields. Enums with no variants are always ignored.
    ///
    /// Functions, traits, type aliases, and types generated by external macros are not checked.
    ///
    /// ### Why restrict this?
    /// Marking a type with `#[must_use]` warns users when a value is discarded without being used.
    /// This can help catch bugs when ignoring resources, handles, or results. This lint lets
    /// library authors require that the annotation is considered for each type in its scope.
    ///
    /// Types that genuinely do not need the attribute can be annotated with
    /// `#[expect(clippy::missing_must_use)]` individually with a justifying comment.
    ///
    /// ### Example
    /// ```no_run
    /// pub struct S(u8);
    /// ```
    /// Use instead:
    /// ```no_run
    /// #[must_use]
    /// pub struct S(u8);
    /// ```
    #[clippy::version = "1.101.0"]
    pub MISSING_MUST_USE,
    restriction,
    "finding types that are not marked with `#[must_use]`"
}

impl_lint_pass!(MissingMustUse => [MISSING_MUST_USE]);

pub struct MissingMustUse {
    check_private_items: bool,
    missing_must_use_on_empty: bool,
}

impl MissingMustUse {
    pub fn new(conf: &'static Conf) -> Self {
        Self {
            check_private_items: conf.check_private_items,
            missing_must_use_on_empty: conf.missing_must_use_on_empty,
        }
    }
}

impl LateLintPass<'_> for MissingMustUse {
    fn check_item(&mut self, cx: &LateContext<'_>, item: &Item<'_>) {
        if item.span.in_external_macro(cx.sess().source_map()) {
            return;
        }
        if !self.check_private_items && !cx.effective_visibilities.is_exported(item.owner_id.def_id) {
            return;
        }

        let is_empty = match item.kind {
            ItemKind::Struct(_, _, data) => data.fields().is_empty(),
            ItemKind::Enum(_, _, def) => match def.variants {
                [] => return,
                [variant] => variant.data.fields().is_empty(),
                _ => false,
            },
            ItemKind::Union(..) => false,
            _ => return,
        };
        if is_empty && !self.missing_must_use_on_empty {
            return;
        }
        if find_attr!(cx.tcx.hir_attrs(item.hir_id()), MustUse { .. }) {
            return;
        }

        let indent = snippet_indent(cx, item.span).unwrap_or_default();
        span_lint_and_sugg(
            cx,
            MISSING_MUST_USE,
            item.span.shrink_to_lo(),
            "missing `#[must_use]` attribute on this type",
            "add `#[must_use]` to this type definition",
            format!("#[must_use]\n{indent}"),
            Applicability::MachineApplicable,
        );
    }
}
